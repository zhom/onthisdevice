import * as React from 'react'

import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from '@/components/ui/select'
import { ToolPanel } from '@/components/shared/ToolPanel'
import { formatBytes } from '@/lib/utils'

import { countLines } from './datautil'
import { DEFAULT_TURNDOWN, createTurndown, tidyMarkdown, type TurndownSettings } from './markdownize'
import { Field, TextConverter, ToggleRow, type ConversionResult } from './ui'

const SAMPLE = `<article>
  <h1>Quarterly update</h1>
  <p>Revenue grew <strong>18%</strong> quarter over quarter, driven by <em>self-serve</em> signups.</p>

  <h2>Highlights</h2>
  <ul>
    <li>Shipped the new <a href="https://example.com/importer">CSV importer</a></li>
    <li>Cut median page load to <code>380ms</code></li>
    <li><del>Migrated the billing service</del> (moved to next quarter)</li>
  </ul>

  <h2>Numbers</h2>
  <table>
    <thead>
      <tr><th>Metric</th><th align="right">Q2</th><th align="right">Q3</th></tr>
    </thead>
    <tbody>
      <tr><td>Active teams</td><td align="right">1,240</td><td align="right">1,463</td></tr>
      <tr><td>Churn</td><td align="right">2.4%</td><td align="right">1.9%</td></tr>
    </tbody>
  </table>

  <blockquote><p>The importer alone saved us a day a week.</p></blockquote>

  <pre><code>npm install onthisdevice</code></pre>
</article>`

function extractBody(html: string): string {
  if (typeof DOMParser === 'undefined') return html
  if (!/<html[\s>]|<body[\s>]|<!doctype/i.test(html)) return html
  const doc = new DOMParser().parseFromString(html, 'text/html')
  return doc.body?.innerHTML ?? html
}

export default function HtmlToMarkdown() {
  const [headingStyle, setHeadingStyle] = React.useState<TurndownSettings['headingStyle']>('atx')
  const [bulletListMarker, setBullet] = React.useState<TurndownSettings['bulletListMarker']>('-')
  const [codeBlockStyle, setCodeBlockStyle] = React.useState<TurndownSettings['codeBlockStyle']>('fenced')
  const [fence, setFence] = React.useState<TurndownSettings['fence']>('```')
  const [emDelimiter, setEm] = React.useState<TurndownSettings['emDelimiter']>('_')
  const [strongDelimiter, setStrong] = React.useState<TurndownSettings['strongDelimiter']>('**')
  const [linkStyle, setLinkStyle] = React.useState<TurndownSettings['linkStyle']>('inlined')
  const [hr, setHr] = React.useState<TurndownSettings['hr']>('---')
  const [tables, setTables] = React.useState(true)
  const [strikethrough, setStrikethrough] = React.useState(true)
  const [taskLists, setTaskLists] = React.useState(true)
  const [images, setImages] = React.useState(true)
  const [bodyOnly, setBodyOnly] = React.useState(true)

  const convert = React.useCallback(
    (input: string): ConversionResult => {
      const settings: TurndownSettings = {
        ...DEFAULT_TURNDOWN,
        headingStyle,
        bulletListMarker,
        codeBlockStyle,
        fence,
        emDelimiter,
        strongDelimiter,
        linkStyle,
        hr,
        tables,
        strikethrough,
        taskLists,
        images,
      }
      const source = bodyOnly ? extractBody(input) : input
      let markdown: string
      try {
        markdown = tidyMarkdown(createTurndown(settings).turndown(source))
      } catch (error) {
        return {
          output: '',
          issue: {
            message:
              error instanceof Error
                ? `That HTML could not be converted: ${error.message}`
                : 'That HTML could not be converted.',
          },
        }
      }
      if (markdown.trim() === '') {
        return {
          output: '',
          issue: {
            message:
              'The HTML produced no text. If you pasted a whole page, check that the content is inside <body> and not generated by JavaScript.',
          },
        }
      }
      const inBytes = new TextEncoder().encode(input).length
      const outBytes = new TextEncoder().encode(markdown).length
      return {
        output: markdown,
        stats: [
          { label: 'lines', value: countLines(markdown).toLocaleString() },
          { label: 'Markdown', value: formatBytes(outBytes) },
          {
            label: 'smaller than the HTML',
            value: inBytes > 0 ? `${Math.max(0, Math.round(((inBytes - outBytes) / inBytes) * 100))}%` : '0%',
          },
        ],
      }
    },
    [
      headingStyle,
      bulletListMarker,
      codeBlockStyle,
      fence,
      emDelimiter,
      strongDelimiter,
      linkStyle,
      hr,
      tables,
      strikethrough,
      taskLists,
      images,
      bodyOnly,
    ],
  )

  return (
    <TextConverter
      idPrefix="html2md"
      inputTitle="HTML input"
      outputTitle="Markdown output"
      placeholder="Paste HTML here, or drop a .html file…"
      accept=".html,.htm,.xhtml,.txt,text/html,text/plain"
      sample={SAMPLE}
      sampleLabel="Sample HTML"
      outputMime="text/markdown"
      convert={convert}
      downloadName={(base) => `${base}.md`}
      emptyHint="Your Markdown will appear here."
      options={
        <ToolPanel title="Markdown style" description="Turndown options, applied live as you change them.">
          <div className="grid gap-3 sm:grid-cols-2 lg:grid-cols-4">
            <Field id="h2m-heading" label="Heading style">
              <Select
                value={headingStyle}
                onValueChange={(v) => setHeadingStyle(v as TurndownSettings['headingStyle'])}
              >
                <SelectTrigger id="h2m-heading">
                  <SelectValue />
                </SelectTrigger>
                <SelectContent>
                  <SelectItem value="atx"># ATX</SelectItem>
                  <SelectItem value="setext">Setext (underlined)</SelectItem>
                </SelectContent>
              </Select>
            </Field>
            <Field id="h2m-bullet" label="Bullet marker">
              <Select
                value={bulletListMarker}
                onValueChange={(v) => setBullet(v as TurndownSettings['bulletListMarker'])}
              >
                <SelectTrigger id="h2m-bullet">
                  <SelectValue />
                </SelectTrigger>
                <SelectContent>
                  <SelectItem value="-">Hyphen  -</SelectItem>
                  <SelectItem value="*">Asterisk  *</SelectItem>
                  <SelectItem value="+">Plus  +</SelectItem>
                </SelectContent>
              </Select>
            </Field>
            <Field id="h2m-code" label="Code blocks">
              <Select
                value={codeBlockStyle}
                onValueChange={(v) => setCodeBlockStyle(v as TurndownSettings['codeBlockStyle'])}
              >
                <SelectTrigger id="h2m-code">
                  <SelectValue />
                </SelectTrigger>
                <SelectContent>
                  <SelectItem value="fenced">Fenced</SelectItem>
                  <SelectItem value="indented">Indented four spaces</SelectItem>
                </SelectContent>
              </Select>
            </Field>
            <Field id="h2m-fence" label="Fence characters">
              <Select
                value={fence}
                onValueChange={(v) => setFence(v as TurndownSettings['fence'])}
                disabled={codeBlockStyle !== 'fenced'}
              >
                <SelectTrigger id="h2m-fence">
                  <SelectValue />
                </SelectTrigger>
                <SelectContent>
                  <SelectItem value="```">Backticks  ```</SelectItem>
                  <SelectItem value="~~~">Tildes  ~~~</SelectItem>
                </SelectContent>
              </Select>
            </Field>
            <Field id="h2m-em" label="Italic delimiter">
              <Select value={emDelimiter} onValueChange={(v) => setEm(v as TurndownSettings['emDelimiter'])}>
                <SelectTrigger id="h2m-em">
                  <SelectValue />
                </SelectTrigger>
                <SelectContent>
                  <SelectItem value="_">_italic_</SelectItem>
                  <SelectItem value="*">*italic*</SelectItem>
                </SelectContent>
              </Select>
            </Field>
            <Field id="h2m-strong" label="Bold delimiter">
              <Select
                value={strongDelimiter}
                onValueChange={(v) => setStrong(v as TurndownSettings['strongDelimiter'])}
              >
                <SelectTrigger id="h2m-strong">
                  <SelectValue />
                </SelectTrigger>
                <SelectContent>
                  <SelectItem value="**">**bold**</SelectItem>
                  <SelectItem value="__">__bold__</SelectItem>
                </SelectContent>
              </Select>
            </Field>
            <Field id="h2m-link" label="Link style">
              <Select value={linkStyle} onValueChange={(v) => setLinkStyle(v as TurndownSettings['linkStyle'])}>
                <SelectTrigger id="h2m-link">
                  <SelectValue />
                </SelectTrigger>
                <SelectContent>
                  <SelectItem value="inlined">Inline: [text](url)</SelectItem>
                  <SelectItem value="referenced">Reference: [text][1]</SelectItem>
                </SelectContent>
              </Select>
            </Field>
            <Field id="h2m-hr" label="Horizontal rule">
              <Select value={hr} onValueChange={(v) => setHr(v as TurndownSettings['hr'])}>
                <SelectTrigger id="h2m-hr">
                  <SelectValue />
                </SelectTrigger>
                <SelectContent>
                  <SelectItem value="---">---</SelectItem>
                  <SelectItem value="***">***</SelectItem>
                  <SelectItem value="___">___</SelectItem>
                </SelectContent>
              </Select>
            </Field>
          </div>
          <div className="mt-3 grid gap-2 sm:grid-cols-2 lg:grid-cols-5">
            <ToggleRow
              id="h2m-tables"
              label="GFM tables"
              hint="Off leaves <table> markup untouched."
              checked={tables}
              onCheckedChange={setTables}
            />
            <ToggleRow
              id="h2m-strike"
              label="Strikethrough"
              checked={strikethrough}
              onCheckedChange={setStrikethrough}
            />
            <ToggleRow id="h2m-tasks" label="Task lists" checked={taskLists} onCheckedChange={setTaskLists} />
            <ToggleRow id="h2m-images" label="Keep images" checked={images} onCheckedChange={setImages} />
            <ToggleRow
              id="h2m-body"
              label="Body only"
              hint="Ignores <head> when you paste a whole page."
              checked={bodyOnly}
              onCheckedChange={setBodyOnly}
            />
          </div>
        </ToolPanel>
      }
    />
  )
}
