export interface GlyphCell {
  x: number
  y: number
  /** Bit p is set when the pixel shows in phase p (0..3). */
  mask: number
}

/** The four phases of a glyph: two frames play as A A B B. */
function phases(frames: readonly Frame[]): readonly Frame[] {
  if (frames.length === 4) return frames
  const [a, b = a] = frames
  return [a, a, b, b]
}

/** Every pixel that shows in at least one phase, with its phase mask. */
export function glyphCells(id: string): GlyphCell[] {
  const frames = phases(GLYPHS[id] ?? GLYPHS.text)
  const cells: GlyphCell[] = []
  for (let y = 0; y < GLYPH_SIZE; y++) {
    for (let x = 0; x < GLYPH_SIZE; x++) {
      let mask = 0
      frames.forEach((frame, p) => {
        if (frame[y]?.[x] === '#') mask |= 1 << p
      })
      if (mask) cells.push({ x, y, mask })
    }
  }
  return cells
}

/** One still frame as an SVG string, for share cards and icons. */
export function glyphSvg(id: string, opts: { phase?: number; fill?: string; size?: number } = {}): string {
  const { phase = 0, fill = 'currentColor', size = 90 } = opts
  const rects = glyphCells(id)
    .filter((c) => c.mask & (1 << phase))
    .map((c) => `<rect x="${c.x + 0.09}" y="${c.y + 0.09}" width="0.82" height="0.82" rx="0.08"/>`)
    .join('')
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${GLYPH_SIZE} ${GLYPH_SIZE}" width="${size}" height="${size}" fill="${fill}">${rects}</svg>`
}
